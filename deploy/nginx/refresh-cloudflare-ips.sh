#!/usr/bin/env bash
# Rewrites cloudflare-ips.inc from Cloudflare's published ranges. Run it from the repository root, commit the result, deploy.
# The file does two jobs: it lets nginx read the caller's real address from CF-Connecting-IP when (and only when) the request comes from
# Cloudflare, and it sets $from_cloudflare, so locations.inc can refuse any request that did not come through Cloudflare.
set -euo pipefail
out="deploy/nginx/cloudflare-ips.inc"
v4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS https://www.cloudflare.com/ips-v6)"
[ -n "$v4" ] && [ -n "$v6" ] || { echo "could not read Cloudflare's ranges"; exit 1; }
{
  echo "# Cloudflare's published address ranges (https://www.cloudflare.com/ips). Generated by refresh-cloudflare-ips.sh; refresh now and then."
  for r in $v4 $v6; do echo "set_real_ip_from $r;"; done
  echo "real_ip_header CF-Connecting-IP;"
  echo
  echo "# 1 when the connection itself (not the header) came from Cloudflare; anything else is refused in locations.inc."
  echo "geo \$realip_remote_addr \$from_cloudflare {"
  echo "    default 0;"
  for r in $v4 $v6; do echo "    $r 1;"; done
  echo "}"
} > "$out"
echo "wrote $out"
