package com.circaso.wallet.data.tables

import org.jetbrains.exposed.v1.core.Table
import org.jetbrains.exposed.v1.core.java.javaUUID
import org.jetbrains.exposed.v1.javatime.timestamp

/** `wallet.fee_wallet_networks` (V13): where each network's fee wallets stand. */
object FeeWalletNetworksTable : Table("wallet.fee_wallet_networks") {
    val network = text("network")
    val walletSetId = text("wallet_set_id").nullable()
    val status = text("status")
    val reason = text("reason").nullable()
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(network)
}

/** `wallet.fee_wallets` (V13): Circaso's fee wallet on each chain. */
object FeeWalletsTable : Table("wallet.fee_wallets") {
    val blockchain = text("blockchain")

    /** Generated by the database from [blockchain]; never written here. */
    val network = text("network").databaseGenerated()
    val address = text("address")
    val circleWalletId = text("circle_wallet_id").nullable()
    val walletSetId = text("wallet_set_id").nullable()
    val origin = text("origin")
    val createdAt = timestamp("created_at")
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(blockchain)
}

/** `wallet.fee_destinations` (V13): where collected fees may be withdrawn to. */
object FeeDestinationsTable : Table("wallet.fee_destinations") {
    val destinationId = javaUUID("destination_id")
    val blockchain = text("blockchain")
    val network = text("network").databaseGenerated()
    val address = text("address")
    val label = text("label")
    val createdBy = javaUUID("created_by")
    val createdByEmail = text("created_by_email")
    val createdAt = timestamp("created_at")
    val removedAt = timestamp("removed_at").nullable()
    val removedBy = javaUUID("removed_by").nullable()
    override val primaryKey = PrimaryKey(destinationId)
}

/** `wallet.fee_withdrawals` (V13): withdrawals of collected fees. */
object FeeWithdrawalsTable : Table("wallet.fee_withdrawals") {
    val withdrawalId = javaUUID("withdrawal_id")
    val blockchain = text("blockchain")
    val network = text("network").databaseGenerated()
    val asset = text("asset")
    val tokenAddress = text("token_address")
    val decimals = short("decimals")
    val amountMinor = decimal("amount_minor", 78, 0)
    val destinationId = javaUUID("destination_id")
    val destinationAddress = text("destination_address")
    val destinationLabel = text("destination_label")
    val circleWalletId = text("circle_wallet_id")
    val tokenId = text("token_id")
    val circleKey = javaUUID("circle_key")
    val state = text("state")
    val circleTxId = text("circle_tx_id").nullable()
    val txHash = text("tx_hash").nullable()
    val failureReason = text("failure_reason").nullable()
    val reason = text("reason")
    val requestedBy = javaUUID("requested_by")
    val requestedByEmail = text("requested_by_email")
    val idempotencyKey = text("idempotency_key")
    val createdAt = timestamp("created_at")
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(withdrawalId)
}

/** `wallet.fee_wallet_settings` (V13): one row. */
object FeeWalletSettingsTable : Table("wallet.fee_wallet_settings") {
    val id = short("id")
    val destinationDelayHours = integer("destination_delay_hours")
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(id)
}
