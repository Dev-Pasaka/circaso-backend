package com.circaso.wallet.data.tables

import org.jetbrains.exposed.v1.core.Table
import org.jetbrains.exposed.v1.core.java.javaUUID
import org.jetbrains.exposed.v1.javatime.timestamp

/** `wallet.network_access` (V12): a person's access to a network beyond the general rule. */
object NetworkAccessTable : Table("wallet.network_access") {
    val userId = javaUUID("user_id")
    val network = text("network")
    val source = text("source")
    val grantedBy = javaUUID("granted_by").nullable()
    val reason = text("reason").nullable()
    val createdAt = timestamp("created_at")
    override val primaryKey = PrimaryKey(userId, network)
}

/** `wallet.network_settings` (V12): one row per network; the row is what a settings change locks. */
object NetworkSettingsTable : Table("wallet.network_settings") {
    val network = text("network")
    val state = text("state")
    val appId = text("app_id")
    val defaultChain = text("default_chain")
    val version = long("version")
    val updatedBy = javaUUID("updated_by").nullable()
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(network)
}

/** `wallet.network_chains` (V12): a network's chains in the order they are offered. */
object NetworkChainsTable : Table("wallet.network_chains") {
    val blockchain = text("blockchain")
    val network = text("network")
    val position = integer("position")
    val enabled = bool("enabled")
    val receiveEnabled = bool("receive_enabled")
    val accountType = text("account_type")
    override val primaryKey = PrimaryKey(blockchain)

    init {
        index("network_chains_network_idx", false, network, position)
    }
}

/** `wallet.network_assets` (V12): the assets offered on a chain, in order. */
object NetworkAssetsTable : Table("wallet.network_assets") {
    val blockchain = text("blockchain")
    val position = integer("position")
    val symbol = text("symbol")
    val tokenAddress = text("token_address")
    val decimals = short("decimals")
    val usdPegged = bool("usd_pegged")
    override val primaryKey = PrimaryKey(blockchain, position)
}

/** `wallet.chain_fees` (V12): Circaso's fee wallet per chain and the fallback price of the chain's own coin. */
object ChainFeesTable : Table("wallet.chain_fees") {
    val blockchain = text("blockchain")

    /** Generated by the database from [blockchain]; never written here. */
    val network = text("network").databaseGenerated()
    val feeAddress = text("fee_address").nullable()
    val nativeUsd = decimal("native_usd", 20, 6).nullable()
    val updatedAt = timestamp("updated_at")
    override val primaryKey = PrimaryKey(blockchain)
}
