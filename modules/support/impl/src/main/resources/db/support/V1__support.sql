-- Support tickets (decision 2026-11-08): users open them from the app (SU1) or through Asha, staff work them from the
-- ops dashboard through SupportDesk. Ids are UUIDv7 made in order on the server, so every list pages by id (keyset)
-- and "created before" is a bound on the id. Enums are stored by name. Never edit this script once applied; a change
-- is a new script.

CREATE TABLE support.tickets (
    ticket_id           uuid        PRIMARY KEY,
    number              bigint      GENERATED BY DEFAULT AS IDENTITY, -- shown as CS-000123
    user_id             uuid        NOT NULL,
    subject             text        NOT NULL,                       -- 3-120 characters, one line
    description         text        NOT NULL,                       -- 10-4,000 characters
    category            text        NOT NULL,                       -- ACCOUNT | PAYMENTS | WALLET | GROUPS | SECURITY | ASHA | OTHER
    status              text        NOT NULL,                       -- OPEN | PENDING_USER | RESOLVED | CLOSED
    source              text        NOT NULL,                       -- APP | ASHA
    context_transfer_id uuid,                                       -- a transfer the user sent, received or signed
    context_chat_id     uuid,                                       -- a chat the user was a member of
    assignee_id         uuid,                                       -- a staff id from the ops module, never an email
    waiting_on          text,                                       -- STAFF | USER; NULL once resolved or closed
    created_at          timestamptz NOT NULL,                       -- the instant inside ticket_id
    updated_at          timestamptz NOT NULL,                       -- every change, notes included
    last_message_at     timestamptz NOT NULL,                       -- what the user can see: never moved by a note
    version             bigint      NOT NULL,
    CONSTRAINT tickets_number_key UNIQUE (number)
);
-- SU2 (the user's list, newest first: a backward scan) and SupportDesk.ofUser; also account deletion.
CREATE INDEX tickets_user_idx ON support.tickets (user_id, ticket_id);
-- The queue by status (OPEN and PENDING_USER oldest first, the others newest first) and the open and pending counts,
-- index-only.
CREATE INDEX tickets_status_idx ON support.tickets (status, ticket_id);
-- "Mine": the queue of one staff member.
CREATE INDEX tickets_assignee_idx ON support.tickets (assignee_id, ticket_id);
-- The queue by category.
CREATE INDEX tickets_category_idx ON support.tickets (category, ticket_id);
-- Nobody on it: the unassigned queue (by status) and the dashboard's "unassigned open" count.
CREATE INDEX tickets_unassigned_idx ON support.tickets (status, ticket_id) WHERE assignee_id IS NULL;

CREATE TABLE support.messages (
    message_id uuid        PRIMARY KEY,
    ticket_id  uuid        NOT NULL REFERENCES support.tickets (ticket_id) ON DELETE CASCADE,
    author     text        NOT NULL,                                -- USER | STAFF | ASHA
    staff_id   uuid,                                                -- set for STAFF only
    body       text        NOT NULL,                                -- 1-4,000 characters
    internal   boolean     NOT NULL,                                -- a staff note: never shown or sent to the user
    created_at timestamptz NOT NULL
);
-- A ticket's thread, oldest first; also what the cascade deletes by.
CREATE INDEX messages_ticket_idx ON support.messages (ticket_id, message_id);

-- The frames support sent, kept 7 days for replay (daily partitions made and dropped by support.purge-expired).
CREATE TABLE support.realtime (
    user_id  uuid        NOT NULL,
    seq      bigint      NOT NULL,
    frame    text        NOT NULL,
    sent_at  timestamptz NOT NULL,
    PRIMARY KEY (user_id, seq, sent_at)
) PARTITION BY RANGE (sent_at);
